//! Writes every golden vector to `<testdata>/vectors/<name>.json` and
//! regenerates `<testdata>/vectors.zig`, which embeds them for tests.
//! Usage: zig build gen-vectors

const std = @import("std");
const vectors = @import("vectors");

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();

    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 2) {
        std.debug.print("usage: gen_vectors <testdata-dir>\n", .{});
        std.process.exit(2);
    }

    var dir = try std.Io.Dir.cwd().openDir(io, args[1], .{});
    defer dir.close(io);
    try dir.createDirPath(io, "vectors");

    var index: std.Io.Writer.Allocating = .init(arena);
    const w = &index.writer;
    try w.writeAll(
        \\//! Generated by `zig build gen-vectors`. Do not edit.
        \\
        \\pub const Entry = struct { name: []const u8, json: []const u8 };
        \\
        \\pub const entries = [_]Entry{
        \\
    );

    for (vectors.cases) |case| {
        const json = try case.generate(arena);
        const path = try std.fmt.allocPrint(arena, "vectors/{s}.json", .{case.name});
        try dir.writeFile(io, .{ .sub_path = path, .data = json });
        try w.print("    .{{ .name = \"{s}\", .json = @embedFile(\"{s}\") }},\n", .{ case.name, path });
        std.debug.print("wrote {s}\n", .{path});
    }
    try w.writeAll("};\n");
    try dir.writeFile(io, .{ .sub_path = "vectors.zig", .data = index.written() });
}
